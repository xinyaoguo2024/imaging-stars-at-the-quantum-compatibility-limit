def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-root", type=Path, default=DEFAULT_RUN_ROOT)
    parser.add_argument("--result-dir", type=Path, default=DEFAULT_RESULT_DIR)
    parser.add_argument("--figure-dir", type=Path, default=DEFAULT_FIGURE_DIR)
    parser.add_argument(
        "--skip-figure",
        action="store_true",
        help="Write the numerical statistics without rendering the superseded wide-layout figure.",
    )
    parser.add_argument("--receiver-cache", type=Path, default=DEFAULT_RECEIVER_CACHE)
    parser.add_argument("--stem", default=DEFAULT_STEM)
    parser.add_argument(
        "--bootstrap-resamples",
        type=int,
        default=DEFAULT_BOOTSTRAP_RESAMPLES,
        help="Number of fixed-seed percentile-bootstrap resamples.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.bootstrap_resamples < 1:
        raise ValueError("--bootstrap-resamples must be positive")

    rows, input_paths, provenance = load_paired_rows(args.run_root)
    values = values_by_strategy(rows)
    strategy_stats, difference_stats, summary_csv_rows = compute_statistics(
        values,
        n_resamples=args.bootstrap_resamples,
    )
    component_chi2 = chi2_statistics(values)
    chi2_receiver_spreads = {}
    for metric in CHI2_METRICS:
        means = np.asarray(
            [component_chi2[strategy.key][metric]["mean"] for strategy in STRATEGIES],
            dtype=float,
        )
        ratio = float(np.max(means) / np.min(means))
        chi2_receiver_spreads[metric] = {
            "minimum_mean": float(np.min(means)),
            "maximum_mean": float(np.max(means)),
            "max_to_min_ratio": ratio,
        }
        if ratio > 1.10 + 1.0e-12:
            raise ValueError(
                f"The three receiver means for {metric} are not matched within 10%: "
                f"max/min={ratio:.4f}. Rerun or inspect the common RML selection."
            )
    loop_gains, loop_gain_stats = load_loop_gains(args.receiver_cache)

    args.result_dir.mkdir(parents=True, exist_ok=True)
    args.figure_dir.mkdir(parents=True, exist_ok=True)
    raw_csv = args.result_dir / f"{args.stem}_seed_metrics.csv"
    stats_csv = args.result_dir / f"{args.stem}_statistics.csv"
    stats_json = args.result_dir / f"{args.stem}_statistics.json"
    chi2_tex = args.result_dir / f"{args.stem}_chi2_table.tex"
    pdf_path = args.figure_dir / f"{args.stem}.pdf"
    png_path = args.figure_dir / f"{args.stem}.png"

    write_csv(raw_csv, rows)
    write_csv(stats_csv, summary_csv_rows)
    write_chi2_table(chi2_tex, component_chi2)
    if not args.skip_figure:
        plot_statistics(
            values,
            strategy_stats,
            loop_gains,
            loop_gain_stats,
            pdf_path=pdf_path,
            png_path=png_path,
        )

    payload = {
        "schema_version": 2,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "analysis": "paired main-text Fig. 4 receiver statistics",
        "metadata": {
            "dataset": "single paired 100-ms ensemble; no legacy or modular inputs",
            "n_station": 6,
            "n_seed": len(SEEDS),
            "seeds": list(SEEDS),
            "strategies": [strategy.key for strategy in STRATEGIES],
            "phase_parameter_space": "closure subspace only",
            "phase_dimension_C": 10,
            "amplitude_parameter_space": "complete edge space",
            "amplitude_dimension_E": 15,
            "coherent_block_size_ns": BLOCK_SIZE,
            "promotion_model": PROMOTION_MODEL,
            "finite_block_interpretation": (
                "finite-copy covariance supplied by the configured receiver cache; "
                "QLAN retained only as an asymptotic loop-gain reference"
            ),
            "paired_noise_draws": True,
            "effective_exposure_s": 0.100,
            "existing_coupled_area_fraction": 1.0,
            "remote_diameter_m": 6.0,
            "photon_collection_efficiency": 0.02,
            "amplitude_branch_fraction": 0.5,
            "phase_branch_fraction": 0.5,
            "reconstruction_selection": (
                "one fixed Gaussian/TV/entropy regularization, with no translation-gauge "
                "or morphology-specific core prior, plus one receiver-blind, data-only "
                "componentwise target chi-square of 0.85 with a 0.75--1.00 "
                "candidate window for every seed and receiver"
            ),
            "bootstrap": {
                "method": "paired nonparametric percentile bootstrap of the mean",
                "confidence_level": 0.95,
                "rng_seed": BOOTSTRAP_SEED,
                "n_resamples": args.bootstrap_resamples,
            },
            **provenance,
        },
        "input_summary_files": [str(path.resolve()) for path in input_paths],
        "strategy_statistics": strategy_stats,
        "paired_difference_statistics": difference_stats,
        "component_chi2_statistics": component_chi2,
        "component_chi2_receiver_spreads": chi2_receiver_spreads,
        "per_loop_snr_gain_statistics": loop_gain_stats,
        "outputs": {
            "seed_metrics_csv": str(raw_csv.resolve()),
            "statistics_csv": str(stats_csv.resolve()),
            "statistics_json": str(stats_json.resolve()),
            "chi2_table_tex": str(chi2_tex.resolve()),
            "figure_pdf": None if args.skip_figure else str(pdf_path.resolve()),
            "figure_png": None if args.skip_figure else str(png_path.resolve()),
        },
    }
    stats_json.write_text(json.dumps(payload, indent=2) + "\n")

    if not args.skip_figure:
        print(pdf_path)
        print(png_path)
    print(raw_csv)
    print(stats_csv)
    print(stats_json)
    print(chi2_tex)


if __name__ == "__main__":
    main()
