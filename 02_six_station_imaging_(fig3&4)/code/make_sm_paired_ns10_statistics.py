def bootstrap_mean_interval(
    values: np.ndarray,
    *,
    rng: np.random.Generator,
    n_resamples: int,
) -> tuple[float, float]:
    if n_resamples < 1:
        raise ValueError("bootstrap resamples must be positive")
    indices = rng.integers(0, values.size, size=(n_resamples, values.size))
    bootstrap_means = np.mean(values[indices], axis=1)
    low, high = np.quantile(bootstrap_means, (0.025, 0.975))
    return float(low), float(high)


def describe(
    values: np.ndarray,
    *,
    rng: np.random.Generator,
    n_resamples: int,
) -> dict[str, float | int]:
    if values.ndim != 1 or values.size != len(SEEDS):
        raise ValueError(f"expected one value for each of {len(SEEDS)} paired seeds")
    sample_std = float(np.std(values, ddof=1))
    ci_low, ci_high = bootstrap_mean_interval(values, rng=rng, n_resamples=n_resamples)
    return {
        "n_seed": int(values.size),
        "mean": float(np.mean(values)),
        "sample_std": sample_std,
        "sem": sample_std / math.sqrt(values.size),
        "bootstrap_ci95_lower": ci_low,
        "bootstrap_ci95_upper": ci_high,
        "min": float(np.min(values)),
        "max": float(np.max(values)),
    }


def compute_statistics(
    values: dict[str, dict[str, np.ndarray]],
    *,
    n_resamples: int,
) -> tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]]]:
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    strategy_stats: dict[str, Any] = {metric: {} for metric in METRICS}
    difference_stats: dict[str, Any] = {metric: {} for metric in METRICS}
    csv_rows: list[dict[str, Any]] = []

    for metric in METRICS:
        for strategy in STRATEGIES:
            stats = describe(values[strategy.key][metric], rng=rng, n_resamples=n_resamples)
            strategy_stats[metric][strategy.key] = stats
            csv_rows.append(
                {
                    "analysis_type": "strategy",
                    "metric": metric,
                    "key": strategy.key,
                    "label": strategy.short_label,
                    "minuend": "",
                    "subtrahend": "",
                    **stats,
                }
            )

        for comparison in COMPARISONS:
            paired_difference = (
                values[comparison.minuend][metric] - values[comparison.subtrahend][metric]
            )
            stats = describe(paired_difference, rng=rng, n_resamples=n_resamples)
            difference_stats[metric][comparison.key] = {
                "definition": comparison.label,
                "minuend": comparison.minuend,
                "subtrahend": comparison.subtrahend,
                "seedwise_values": [float(item) for item in paired_difference],
                **stats,
            }
            csv_rows.append(
                {
                    "analysis_type": "paired_difference",
                    "metric": metric,
                    "key": comparison.key,
                    "label": comparison.label,
                    "minuend": comparison.minuend,
                    "subtrahend": comparison.subtrahend,
                    **stats,
                }
            )
    return strategy_stats, difference_stats, csv_rows


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        raise ValueError(f"refusing to write empty CSV {path}")
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def correlation_ylim(metric_values: list[np.ndarray]) -> tuple[float, float]:
    values = np.concatenate(metric_values)
    span = max(float(np.ptp(values)), 0.025)
    pad = 0.16 * span
    lower = max(-1.0, float(np.min(values)) - pad)
    upper = min(1.0, float(np.max(values)) + pad)
    if upper - lower < 0.08:
        center = 0.5 * (upper + lower)
        lower = max(-1.0, center - 0.04)
        upper = min(1.0, center + 0.04)
    return lower, upper


def load_loop_gains(cache_path: Path) -> tuple[dict[str, np.ndarray], dict[str, Any]]:
    """Return local closure-SNR gains for every wavelength--epoch sample.

    The cached matrices are nuisance-marginalized covariances in the physical
    balanced-loop coordinates.  Hence the local Fisher information for loop l
    is the reciprocal diagonal variance, and the SNR gain of strategy b over a
    is sqrt(Cov_a,ll/Cov_b,ll).  We summarize the 360 positive local ratios by
    their geometric mean; 5--95% sample quantiles show uv/time variation.
    """
    if not cache_path.is_file():
        raise FileNotFoundError(f"missing receiver cache: {cache_path}")
    with np.load(cache_path) as payload:
        required = {
            "cov_edge_uniform",
            "cov_optimal_singlecopy",
            "cov_promoted_singlecopy",
            "cov_promoted_qlan",
        }
        missing = required.difference(payload.files)
        if missing:
            raise InputValidationError(
                f"receiver cache {cache_path} is missing {sorted(missing)}"
            )
        covariance = {key: np.asarray(payload[key], dtype=float) for key in required}

    expected_shape = (10, 36, 25, 25)
    for key, value in covariance.items():
        if value.shape != expected_shape:
            raise InputValidationError(
                f"receiver cache {key} has shape {value.shape}, expected {expected_shape}"
            )
    variances = {
        key: np.diagonal(value, axis1=-2, axis2=-1)[..., N_EDGE:]
        for key, value in covariance.items()
    }
    for key, value in variances.items():
        if value.shape != (10, 36, len(LOOP_LABELS)):
            raise InputValidationError(f"unexpected loop-variance shape for {key}: {value.shape}")
        if not np.all(np.isfinite(value)) or np.any(value <= 0.0):
            raise InputValidationError(f"nonpositive or nonfinite loop variance for {key}")

    gains = {
        "optimal_vs_edge": np.sqrt(
            variances["cov_edge_uniform"] / variances["cov_optimal_singlecopy"]
        ),
        "promoted_vs_edge": np.sqrt(
            variances["cov_edge_uniform"] / variances["cov_promoted_singlecopy"]
        ),
        "promoted_vs_parent": np.sqrt(
            variances["cov_optimal_singlecopy"]
            / variances["cov_promoted_singlecopy"]
        ),
        "qlan_vs_edge": np.sqrt(
            variances["cov_edge_uniform"] / variances["cov_promoted_qlan"]
        ),
        "qlan_vs_parent": np.sqrt(
            variances["cov_optimal_singlecopy"]
            / variances["cov_promoted_qlan"]
        ),
    }

    def summarize(array: np.ndarray) -> dict[str, Any]:
        per_loop = []
        for label, values in zip(LOOP_LABELS, np.moveaxis(array, -1, 0), strict=True):
            flat = values.reshape(-1)
            per_loop.append(
                {
                    "loop": label,
                    "n_wavelength_epoch_samples": int(flat.size),
                    "geometric_mean": float(np.exp(np.mean(np.log(flat)))),
                    "arithmetic_mean": float(np.mean(flat)),
                    "median": float(np.median(flat)),
                    "quantile_05": float(np.quantile(flat, 0.05)),
                    "quantile_95": float(np.quantile(flat, 0.95)),
                    "minimum": float(np.min(flat)),
                    "maximum": float(np.max(flat)),
                }
            )
        return {
            "definition": "local SNR gain from reciprocal nuisance-marginalized loop variance",
            "aggregation": "geometric mean over 10 wavelength bins x 36 epochs; 5--95% sample quantiles",
            "per_loop": per_loop,
            "all_samples_geometric_mean": float(np.exp(np.mean(np.log(array)))),
            "all_samples_minimum": float(np.min(array)),
            "all_samples_maximum": float(np.max(array)),
        }

    statistics = {key: summarize(value) for key, value in gains.items()}
    statistics["receiver_cache"] = str(cache_path.resolve())
    return gains, statistics


