class InputValidationError(RuntimeError):
    """Raised when a summary is not from the required paired ensemble."""


def summary_path(run_root: Path, seed: int) -> Path:
    run_tag = f"paired_povm_100ms_seed{seed}_{RUN_SUFFIX}"
    stem = f"broad_plume_split_objective_nmode_rml_{run_tag}_summary.json"
    return run_root / f"seed_{seed}" / "rml_outputs" / stem


def _require(condition: bool, path: Path, message: str) -> None:
    if not condition:
        raise InputValidationError(f"Invalid paired summary {path}: {message}")


def _as_finite_float(value: Any, *, path: Path, field: str) -> float:
    try:
        result = float(value)
    except (TypeError, ValueError) as exc:
        raise InputValidationError(
            f"Invalid paired summary {path}: {field} is not numeric"
        ) from exc
    if not math.isfinite(result):
        raise InputValidationError(
            f"Invalid paired summary {path}: {field} is not finite"
        )
    return result


def _validate_summary(path: Path, seed: int) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    try:
        payload = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        raise InputValidationError(f"Malformed JSON in {path}: {exc}") from exc

    stats = payload.get("stats")
    _require(isinstance(stats, dict), path, "missing object 'stats'")
    assert isinstance(stats, dict)
    expected_keys = {item.key for item in STRATEGIES}

    rows = payload.get("rows")
    _require(isinstance(rows, list), path, "missing list 'rows'")
    assert isinstance(rows, list)
    row_keys = [row.get("strategy") for row in rows if isinstance(row, dict)]
    _require(
        len(rows) == len(STRATEGIES) and set(row_keys) == expected_keys and len(set(row_keys)) == len(row_keys),
        path,
        f"expected exactly {sorted(expected_keys)}, found {row_keys}",
    )

    _require(int(stats.get("n_station", -1)) == 6, path, "n_station must be 6")
    _require(
        int(stats.get("n_edge_amplitude", -1)) == 15,
        path,
        "amplitude data must span the full E=15 edge space",
    )
    _require(
        int(stats.get("n_closure_phase", -1)) == 10,
        path,
        "phase data must span only the C=10 closure subspace",
    )
    _require(
        stats.get("phase_parameter_space") == "closure subspace only",
        path,
        "phase_parameter_space must be 'closure subspace only'",
    )
    _require(
        str(stats.get("closure_data_representation", "")).startswith(
            "real-valued local closure coordinates"
        ),
        path,
        "closure data must retain the locally unwrapped POVM coordinates",
    )
    _require(
        stats.get("amplitude_parameter_space") == "complete E-dimensional edge space",
        path,
        "amplitude_parameter_space must be 'complete E-dimensional edge space'",
    )
    _require(
        stats.get("promotion_model") == PROMOTION_MODEL,
        path,
        f"promotion_model must be {PROMOTION_MODEL!r}",
    )
    _require(
        int(stats.get("coherent_block_size", -1)) == BLOCK_SIZE,
        path,
        f"coherent_block_size must be n_s={BLOCK_SIZE}",
    )
    _require(
        abs(
            float(stats.get("finite_ns_qlan_fisher_factor", 1.0))
            - FINITE_NS_QLAN_FISHER_FACTOR
        )
        <= 1.0e-12,
        path,
        "finite_ns_qlan_fisher_factor does not match the requested ensemble",
    )
    _require(stats.get("paired_noise_draws") is True, path, "paired_noise_draws must be true")
    _require(
        abs(float(stats.get("existing_coupled_area_fraction", -1.0)) - 1.0) <= 1.0e-12,
        path,
        "existing-station coupled area fraction must equal 1",
    )
    _require(
        abs(float(stats.get("remote_diameter_m", -1.0)) - 6.0) <= 1.0e-12,
        path,
        "remote-station diameter must equal 6 m",
    )
    _require(
        abs(float(stats.get("photon_collection_efficiency", -1.0)) - 0.02) <= 1.0e-12,
        path,
        "photon collection efficiency must equal 0.02",
    )
    for branch in ("amplitude_branch_fraction", "phase_branch_fraction"):
        value = _as_finite_float(stats.get(branch), path=path, field=f"stats.{branch}")
        _require(abs(value - 0.5) <= 1.0e-12, path, f"{branch} must equal 0.5")

    stress = stats.get("sample_stress_test")
    _require(isinstance(stress, dict), path, "missing stats.sample_stress_test")
    assert isinstance(stress, dict)
    exposure = _as_finite_float(
        stress.get("effective_exposure_s"),
        path=path,
        field="stats.sample_stress_test.effective_exposure_s",
    )
    _require(abs(exposure - 0.100) <= 1.0e-12, path, "effective exposure must be 100 ms")
    _require(
        int(stress.get("rng_seed", -1)) == seed,
        path,
        f"stored rng_seed must equal directory seed {seed}",
    )
    _require(
        stress.get("run_tag") == f"paired_povm_100ms_seed{seed}_{RUN_SUFFIX}",
        path,
        "run_tag does not match the required paired 100-ms ensemble",
    )
    fixed_settings = {
        "rml_prior_weight": 0.01,
        "rml_tv_weight": 0.01,
        "rml_entropy_weight": 0.005,
        "rml_amp_chi2_target": 0.85,
        "rml_amp_chi2_min": 0.75,
        "rml_amp_chi2_max": 1.00,
        "rml_phase_chi2_target": 0.85,
        "rml_phase_chi2_min": 0.75,
        "rml_phase_chi2_max": 1.00,
    }
    for key, expected in fixed_settings.items():
        value = _as_finite_float(
            stress.get(key), path=path, field=f"stats.sample_stress_test.{key}"
        )
        _require(
            abs(value - expected) <= 1.0e-12,
            path,
            f"{key} must equal the common value {expected}",
        )
    _require(
        stress.get("rml_morphology_specific_core_prior") == "none",
        path,
        "no morphology-specific single-core prior may be present",
    )

    clean_rows: list[dict[str, Any]] = []
    for row in rows:
        assert isinstance(row, dict)
        strategy = str(row["strategy"])
        clean: dict[str, Any] = {
            "seed": seed,
            "strategy": strategy,
            "label": STRATEGY_BY_KEY[strategy].short_label,
            "exposure_s": exposure,
            "phase_space": "closure",
            "phase_dimension": 10,
            "amplitude_space": "full_edge",
            "amplitude_dimension": 15,
            "coherent_block_size": BLOCK_SIZE,
            "promotion_model": PROMOTION_MODEL,
            "finite_ns_qlan_fisher_factor": FINITE_NS_QLAN_FISHER_FACTOR,
            "summary_path": str(path.resolve()),
        }
        for metric in METRICS:
            value = _as_finite_float(row.get(metric), path=path, field=f"rows[{strategy}].{metric}")
            _require(-1.0 <= value <= 1.0, path, f"rows[{strategy}].{metric} lies outside [-1,1]")
            clean[metric] = value
        for metric in CHI2_METRICS:
            value = _as_finite_float(row.get(metric), path=path, field=f"rows[{strategy}].{metric}")
            _require(
                0.70 <= value <= 1.10,
                path,
                f"rows[{strategy}].{metric} must lie in [0.70,1.10]",
            )
            clean[metric] = value
        clean_rows.append(clean)

    provenance = {
        "receiver_cache_npz": str(stats.get("receiver_cache_npz", "")),
        "mixed_likelihood": str(stats.get("mixed_likelihood", "")),
    }
    return clean_rows, provenance


def load_paired_rows(run_root: Path) -> tuple[list[dict[str, Any]], list[Path], dict[str, Any]]:
    paths = [summary_path(run_root, seed) for seed in SEEDS]
    missing = [path for path in paths if not path.is_file()]
    if missing:
        listing = "\n".join(f"  - {path}" for path in missing)
        raise FileNotFoundError(
            "The paired 100-ms ensemble is incomplete; the following required seed summaries "
            f"are missing:\n{listing}\nRun run_promoted_povm_ensemble.py before this script."
        )

    all_rows: list[dict[str, Any]] = []
    common_provenance: dict[str, Any] | None = None
    for seed, path in zip(SEEDS, paths, strict=True):
        rows, provenance = _validate_summary(path, seed)
        if common_provenance is None:
            common_provenance = provenance
        else:
            _require(
                provenance == common_provenance,
                path,
                "receiver-cache or likelihood provenance differs across paired seeds",
            )
        all_rows.extend(rows)
    return all_rows, paths, common_provenance or {}


def values_by_strategy(rows: Iterable[dict[str, Any]]) -> dict[str, dict[str, np.ndarray]]:
    rows = list(rows)
    output: dict[str, dict[str, np.ndarray]] = {}
    for strategy in STRATEGIES:
        selected = sorted(
            (row for row in rows if row["strategy"] == strategy.key),
            key=lambda row: int(row["seed"]),
        )
        if [int(row["seed"]) for row in selected] != list(SEEDS):
            raise InputValidationError(f"Strategy {strategy.key} does not contain the exact paired seed set")
        output[strategy.key] = {
            metric: np.asarray([float(row[metric]) for row in selected], dtype=float)
            for metric in (*METRICS, *CHI2_METRICS)
        }
    return output


def chi2_statistics(
    values: dict[str, dict[str, np.ndarray]],
) -> dict[str, dict[str, dict[str, float]]]:
    output: dict[str, dict[str, dict[str, float]]] = {}
    for strategy in STRATEGIES:
        output[strategy.key] = {}
        for metric in CHI2_METRICS:
            sample = values[strategy.key][metric]
            sample_std = float(np.std(sample, ddof=1))
            output[strategy.key][metric] = {
                "mean": float(np.mean(sample)),
                "sem": sample_std / math.sqrt(sample.size),
                "sample_std": sample_std,
            }
    return output


