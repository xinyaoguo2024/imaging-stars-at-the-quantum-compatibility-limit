def plot_summary(results: list[dict]) -> tuple[Path, Path]:
    fig, axes = plt.subplots(len(results), 4, figsize=(8.6, 2.25 * len(results)), constrained_layout=True)
    if len(results) == 1:
        axes = axes[None, :]
    plt.rcParams.update(
        {
            "font.size": 7.0,
            "axes.labelsize": 7.0,
            "axes.titlesize": 7.4,
            "xtick.labelsize": 6.1,
            "ytick.labelsize": 6.1,
        }
    )
    cols = [
        ("truth", "Input"),
        ("all_amp_phase_rml", "All vis. + drift"),
        ("split_amp_phase_rml", "Edge-first closure"),
        ("direct_amp_phase_rml", "Direct closure"),
    ]
    image_axes = []
    short_labels = {
        "maunakea_top4_plus3_ngc4151": "Hawaii+3",
        "maunakea_top4_plus5_ngc4151": "Hawaii+5",
        "optimal8_ngc4151_hub_m2_m5": "Optimized 8",
    }
    for row, result in enumerate(results):
        axis_uas = result["axis_uas"]
        extent = [axis_uas[0], axis_uas[-1], axis_uas[0], axis_uas[-1]]
        case = result["case"]
        for col, (key, title) in enumerate(cols):
            ax = axes[row, col]
            image = result["images"][key]
            ax.imshow(opt.normalize_blr_display(image), origin="lower", extent=extent, cmap="inferno")
            if key == "truth":
                ax.set_title(title)
            else:
                m = result["metrics"][key]
                ax.set_title(f"{title}\nBLR={m['blr_corr']:.2f}, rad={m['radial_corr']:.2f}")
            ax.set_xlabel(r"$\Delta\alpha$ ($\mu$as)")
            if col == 0:
                ax.set_ylabel(f"{short_labels.get(case.key, case.key)}\n" + r"$\Delta\delta$ ($\mu$as)", fontsize=7.0)
            else:
                ax.set_yticklabels([])
            image_axes.append(ax)
    cbar = fig.colorbar(
        plt.cm.ScalarMappable(norm=colors.Normalize(vmin=0.0, vmax=1.0), cmap="inferno"),
        ax=image_axes,
        fraction=0.018,
        pad=0.012,
    )
    cbar.set_label("normalized brightness", fontsize=6.6)
    fig.suptitle(
        (
            "Reliable-amplitude RML: amplitudes + closure-protected phases; "
            f"{SOURCE.name}, {OBSERVING_DAYS} d, loss {FIBER_LOSS_DB_PER_KM:g} dB/km"
        ),
        fontsize=9.6,
        weight="bold",
    )
    tag = (
        f"eht_style_amp_closure_rml_{SOURCE.key}_{OBSERVING_DAYS}d_"
        f"{N_TIME_WINDOWS}x{EXPOSURE_S/60:g}min_loss{FIBER_LOSS_DB_PER_KM:g}_{sigma_tag()}_n{N_RML}"
    ).replace(".", "p")
    png = OUTFIG / f"{tag}.png"
    pdf = OUTFIG / f"{tag}.pdf"
    fig.savefig(png, dpi=260, bbox_inches="tight")
    fig.savefig(pdf, bbox_inches="tight")
    plt.close(fig)
    return pdf, png


def write_metrics(results: list[dict]) -> tuple[Path, Path]:
    rows: list[dict[str, float | str]] = []
    for result in results:
        for key, metric in result["metrics"].items():
            rows.append({"case": result["case"].key, "image": key, **metric})
    csv_path = OUTFIG / "eht_style_amp_closure_rml_metrics.csv"
    with csv_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    summary = {
        "source": SOURCE.name,
        "source_note": SOURCE.note,
        "cases": [result["stats"] for result in results],
        "metrics_csv": str(csv_path),
    }
    json_path = OUTFIG / "eht_style_amp_closure_rml_summary.json"
    json_path.write_text(json.dumps(summary, indent=2) + "\n")
    return csv_path, json_path


