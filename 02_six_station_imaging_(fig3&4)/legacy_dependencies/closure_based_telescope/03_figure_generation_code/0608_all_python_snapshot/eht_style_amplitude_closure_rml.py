def rms(x: np.ndarray) -> float:
    value = float(np.sqrt(np.mean(np.asarray(x, dtype=float) ** 2)))
    return value if np.isfinite(value) and value > 1e-30 else 1.0


def normalize_grad(grad: np.ndarray) -> np.ndarray:
    scale = rms(grad)
    if scale <= 1e-30:
        return np.zeros_like(grad)
    return grad / scale


def amplitude_sigma(amp_data: np.ndarray, amp_sigma: np.ndarray | None = None) -> np.ndarray:
    """Return the amplitude uncertainty used by the RML likelihood.

    The default ``physical`` mode uses the per-sample visibility-amplitude
    uncertainty generated by the detector-noise model in ``simulate_bands``.
    Constant and relative modes are retained behind environment switches for
    controlled comparisons only.
    """
    amp_data = np.asarray(amp_data, dtype=float)
    if AMP_SIGMA_MODE == "physical":
        if amp_sigma is None:
            return np.full_like(amp_data, AMP_SIGMA_ABS, dtype=float)
        return np.asarray(amp_sigma, dtype=float)
    if AMP_SIGMA_MODE == "relative":
        return AMP_REL_SIGMA * np.maximum(amp_data, AMP_ABS_FLOOR)
    if AMP_SIGMA_MODE != "constant":
        raise ValueError(f"Unknown AMP_RML_AMP_SIGMA_MODE={AMP_SIGMA_MODE!r}")
    return np.full_like(amp_data, AMP_SIGMA_ABS, dtype=float)


def sigma_tag() -> str:
    if AMP_SIGMA_MODE == "physical":
        amp_fp = getattr(wt, "AMPLITUDE_MODE_FALSE_POSITIVE", getattr(aug, "MODE_FALSE_POSITIVE", 0.05))
        return f"ampphys_ampfp{amp_fp:g}"
    if AMP_SIGMA_MODE == "relative":
        return f"amprel{100.0 * AMP_REL_SIGMA:g}pct"
    return f"ampabs{AMP_SIGMA_ABS:g}"


def project_flux_positive(image: np.ndarray, smooth_pix: float = 0.0) -> np.ndarray:
    out = np.clip(image, 0.0, None)
    if smooth_pix > 0.15:
        out = np.clip(base.gaussian_filter(out, smooth_pix), 0.0, None)
    total = float(np.sum(out))
    if not np.isfinite(total) or total <= 0.0:
        out = np.ones_like(image)
        total = float(np.sum(out))
    return out / total


def fft_vis(image: np.ndarray) -> np.ndarray:
    return np.fft.fftshift(np.fft.fft2(np.fft.ifftshift(image)))


def adjoint_image(grid_gradient: np.ndarray) -> np.ndarray:
    n = grid_gradient.shape[0]
    return (n * n) * np.fft.fftshift(np.fft.ifft2(np.fft.ifftshift(grid_gradient))).real


def broad_gaussian_prior(axis_uas: np.ndarray, fwhm_uas: float = 95.0) -> np.ndarray:
    xx, yy = np.meshgrid(axis_uas, axis_uas)
    sigma = fwhm_uas / 2.355
    prior = np.exp(-0.5 * (xx * xx + yy * yy) / sigma**2)
    return project_flux_positive(prior)


def bilinear_adjoint_samples(
    grid: np.ndarray,
    uv_axis: np.ndarray,
    u: np.ndarray,
    v: np.ndarray,
    coeff: np.ndarray,
) -> None:
    """Scatter sample-space complex gradients to the FFT grid.

    This is the adjoint of ``base.interp_vis`` up to the explicit Hermitian
    completion needed for a real image.  The older scripts used nearest-cell
    scattering, which is fast but can bias sparse long-baseline gradients.
    """
    n = grid.shape[0]
    du = uv_axis[1] - uv_axis[0]

    def scatter(us: np.ndarray, vs: np.ndarray, cs: np.ndarray) -> None:
        fu = (us - uv_axis[0]) / du
        fv = (vs - uv_axis[0]) / du
        iu = np.floor(fu).astype(int)
        iv = np.floor(fv).astype(int)
        valid = (iu >= 0) & (iu < n - 1) & (iv >= 0) & (iv < n - 1) & np.isfinite(cs)
        if not np.any(valid):
            return
        iu = iu[valid]
        iv = iv[valid]
        tu = fu[valid] - iu
        tv = fv[valid] - iv
        cv = cs[valid]
        flat = grid.reshape(-1)
        for dx, dy, weight in (
            (0, 0, (1.0 - tu) * (1.0 - tv)),
            (1, 0, tu * (1.0 - tv)),
            (0, 1, (1.0 - tu) * tv),
            (1, 1, tu * tv),
        ):
            np.add.at(flat, (iv + dy) * n + (iu + dx), weight * cv)

    scatter(u, v, coeff)
    scatter(-u, -v, np.conj(coeff))


